const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('D:/HBuilderX/plugins/compile-typescript/node_modules/typescript/lib/typescript.js');
const { loadSetup } = require('./setup-harness.cjs');
const source = fs.readFileSync('api/notifications.uts', 'utf8');
assert.equal(ts.createSourceFile('notifications.ts', source, ts.ScriptTarget.Latest, true).parseDiagnostics.length, 0);
const jsonSource = fs.readFileSync('common/json.uts', 'utf8');
const json = { exports: {} };
new Function('module', 'exports', ts.transpileModule(jsonSource, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(json, json.exports);
const moduleData = { exports: {} };
new Function('require', 'module', 'exports', ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(p => p.includes('json.uts') ? json.exports : {}, moduleData, moduleData.exports);
const api = moduleData.exports;
const result = data => ({ ok: true, data: { data } });
const item = { notificationId: 'abc', title: '订单状态更新', content: '待取货', orderId: 7, createdAt: '2026-10-28', readAt: null };
assert.equal(api.parseNotificationPage(result({items:[item],hasMore:false,nextCursor:null})).items[0].orderId, 7);
assert.equal(api.parseNotificationPage(result({items:[item],hasMore:true,nextCursor:null})), null);
assert.equal(api.parseNotificationPage({ok:false,data:null}), null);
const page = fs.readFileSync('pages/notifications/list.uvue', 'utf8');
const script = page.match(/<script[^>]*>([\s\S]*?)<\/script>/)[1];
loadSetup(script, () => ({}));
console.log('Notification response validation and page script syntax checks passed.');
